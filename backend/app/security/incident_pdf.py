from fpdf import FPDF
from datetime import datetime

class IncidentReport(FPDF):
    def header(self):
        # Khusela Brand Header
        self.set_font('helvetica', 'B', 20)
        self.set_text_color(9, 12, 15) # Obsidian
        self.cell(0, 10, 'KHUSELA', border=False, align='L')
        
        self.set_font('helvetica', '', 10)
        self.set_text_color(100, 116, 139) # Slate
        self.cell(0, 10, 'Secure the bag. Protect the business.', border=False, align='R')
        self.ln(15)
        
        # Divider line
        self.set_draw_color(226, 232, 240) # Border
        self.line(10, 25, 200, 25)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f'Generated by Khusela Security on {datetime.now().strftime("%Y-%m-%d %H:%M")} | Page ' + str(self.page_no()), 0, 0, 'C')

def generate_incident_pdf(incident_data: dict, audit_logs: list) -> bytes:
    pdf = IncidentReport()
    pdf.add_page()
    
    # 1. Case Overview
    pdf.set_font('helvetica', 'B', 14)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, f"Incident Report: {incident_data['id']}", ln=True)
    
    pdf.set_font('helvetica', '', 11)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 8, f"Status: {incident_data['status']}", ln=True)
    pdf.cell(0, 8, f"Date Logged: {incident_data['date']}", ln=True)
    pdf.ln(5)
    
    # 2. Description
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Incident Details", ln=True)
    pdf.set_font('helvetica', '', 11)
    pdf.multi_cell(0, 8, f"Title: {incident_data['title']}")
    pdf.multi_cell(0, 8, f"Description: {incident_data['description']}")
    pdf.ln(5)

    # 3. Evidence & Findings (Structured format)
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Findings & Analysis", ln=True)
    pdf.set_font('helvetica', '', 11)
    pdf.multi_cell(0, 8, "The Khusela Deterministic Engine flagged this incident based on the following extracted evidence. Please note: AI analysis is supplementary. Only a bank can confirm financial settlement.")
    pdf.ln(5)

    # 4. Audit Timeline (Crucial for SAPS)
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Audit Timeline (Tamper-Evident)", ln=True)
    
    pdf.set_font('helvetica', 'B', 10)
    pdf.set_fill_color(248, 250, 252)
    pdf.cell(40, 8, "Timestamp", border=1, fill=True)
    pdf.cell(40, 8, "Event Type", border=1, fill=True)
    pdf.cell(110, 8, "Description", border=1, fill=True)
    pdf.ln()

    pdf.set_font('helvetica', '', 9)
    for log in audit_logs:
        # Shorten timestamp for PDF
        ts = log['timestamp'][:19].replace('T', ' ')
        pdf.cell(40, 8, ts, border=1)
        pdf.cell(40, 8, log['event_type'], border=1)
        # Truncate description if too long
        desc = log['description'][:60] + "..." if len(log['description']) > 60 else log['description']
        pdf.cell(110, 8, desc, border=1)
        pdf.ln()

    pdf.ln(15)
    pdf.set_font('helvetica', 'I', 9)
    pdf.set_text_color(100, 116, 139)
    pdf.multi_cell(0, 6, "Disclaimer: This report is generated from user-submitted evidence. Khusela does not verify bank settlement. Cryptograhpic hashes are maintained in the application audit log to ensure tamper-evidence.")

    # Output to bytes
    return pdf.output()