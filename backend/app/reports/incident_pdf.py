from fpdf import FPDF
from datetime import datetime, timezone, timedelta

class IncidentReport(FPDF):
    def header(self):
        # Khusela Brand Header
        self.set_font('helvetica', 'B', 20)
        self.set_text_color(9, 12, 15) # Obsidian
        # Width 100 for left, width 90 for right
        self.cell(100, 10, 'KHUSELA', border=0, align='L')
        
        self.set_font('helvetica', '', 10)
        self.set_text_color(100, 116, 139) # Slate
        self.cell(90, 10, 'Secure the bag. Protect the business.', border=0, align='R')
        self.ln(15)
        
        # Divider line
        self.set_draw_color(226, 232, 240) # Border
        self.line(10, 25, 200, 25)
        self.ln(10)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        
        sast = datetime.now(timezone.utc) + timedelta(hours=2)
        time_str = sast.strftime("%Y-%m-%d %H:%M SAST")
        
        self.cell(0, 10, f'Generated by Khusela on {time_str} | Page ' + str(self.page_no()), 0, 0, 'C')

def generate_incident_pdf(incident_data: dict, audit_logs: list) -> bytes:
    pdf = IncidentReport()
    pdf.add_page()
    
    # 1. Case Overview
    pdf.set_font('helvetica', 'B', 14)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, f"Incident Report: {incident_data['id']}", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font('helvetica', '', 11)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 8, f"Status: {incident_data['status']}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 8, f"Date Logged: {incident_data['date']}", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)
    
    # 2. Description
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Incident Details", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font('helvetica', '', 11)
    pdf.set_text_color(50, 50, 50)
    
    # Force X back to left margin for multi_cell
    pdf.set_x(10) 
    pdf.multi_cell(0, 8, f"Title: {incident_data['title']}")
    pdf.set_x(10)
    pdf.multi_cell(0, 8, f"Description: {incident_data['description']}")
    pdf.ln(5)

    # 3. Findings
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Findings & Analysis", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font('helvetica', '', 11)
    pdf.set_text_color(50, 50, 50)
    pdf.set_x(10)
    pdf.multi_cell(0, 8, "Khusela flagged this incident based on the provided evidence. Please note: Only your bank can confirm financial settlement.")
    pdf.ln(5)

    # 4. Audit Timeline
    pdf.set_font('helvetica', 'B', 12)
    pdf.set_text_color(9, 12, 15)
    pdf.cell(0, 10, "Audit Timeline (Tamper-Evident)", new_x="LMARGIN", new_y="NEXT")
    
    pdf.set_font('helvetica', 'B', 10)
    pdf.set_fill_color(248, 250, 252)
    pdf.cell(45, 8, "Timestamp", border=1, fill=True)
    pdf.cell(40, 8, "Event Type", border=1, fill=True)
    pdf.cell(105, 8, "Description", border=1, fill=True)
    pdf.ln()

    pdf.set_font('helvetica', '', 9)
    for log in audit_logs:
        ts = log['timestamp'][:19].replace('T', ' ')
        
        # Truncate text to prevent horizontal overflow
        event_type = log['event_type'][:18]
        desc = log['description']
        if len(desc) > 55:
            desc = desc[:52] + "..."
            
        pdf.cell(45, 8, ts, border=1)
        pdf.cell(40, 8, event_type, border=1)
        pdf.cell(105, 8, desc, border=1)
        pdf.ln()

    pdf.ln(15)
    pdf.set_font('helvetica', 'I', 9)
    pdf.set_text_color(100, 116, 139)
    pdf.set_x(10)
    pdf.multi_cell(0, 6, "Disclaimer: This report is generated from user-submitted evidence. Khusela does not verify bank settlement.")

    # Return as bytes
    return bytes(pdf.output())